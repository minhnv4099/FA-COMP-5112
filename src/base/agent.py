    def _convert_to_seq_message(self, input: Union[str, PromptValue]):
        if isinstance(input, str):
            return [HumanMessage(content=input)]
        elif isinstance(input, PromptValue):
            return input.to_messages()

        return input

    def loop_invoke(
            self,
            input: Union[str, PromptValue, Sequence[BaseMessage]],
            config: Optional[RunnableConfig] = None,
            *,
            stop: Optional[list[str]] = None
    ):

        ai_message = self.invoke(input, config, stop=stop)

        tool_calls = ai_message.tool_calls

        messages = [*self._convert_to_seq_message(input), ai_message]

        if tool_calls:
            for tool_call in tool_calls:
                tool_message = self.create_tool_message(
                    content=self._execute_tool(tool_call),
                    _id=tool_call['id']
                )

                messages.append(tool_message)

        return messages

    def _execute_tool(self, tool_call: Union[ToolCall, dict]):
        tool = load_tool(tool_call['name'])

        return tool.invoke(input=tool_call['args'])


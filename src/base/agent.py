    # @deprecated("Use `_get_tool_calls` instead")
    def _parse_output(self, ai_message: AIMessage) -> Any:
        """Parse the structured output in raw ai message in ``tool_calls``

        Get only the last shema in ``tool_calls``
        """

        try:
            dict_output = ai_message.tool_calls[-1]['args']
            # expect structure has only the first field
            key = list(dict_output.keys())[0]
            return dict_output[key]

        except (IndexError, ValueError, KeyError):
            # try to parse when the content may be ```json\n{}\n```
            return self._parse_json_content(ai_message.content)

    def _parse_json_content(self, text: str):
        """Parse the structured output from text content"""

        import json, re

        text = text.strip()
        if text.startswith("```"):
            text = re.sub(r"^```[a-zA-Z]*", "", text).strip("` \n")
        match = re.search(r"\{.*\}", text, re.DOTALL)

        if match:
            try:
                return json.loads(match.group())
            except ValueError:
                pass

        return text

    @override
    def _validate_schemas(self):
        """Initialize schemas including model output (from chat) + tool schemas (from agent)"""

        self.tool_schemas = self._convert_to_list(seq=self.tool_schemas)
        self.output_schema = self._convert_to_list(seq=self.output_schema)

        schemas = self.tool_schemas + self.output_schema
        schemas = [
            self.fetch_schema(tool_schema)
            for tool_schema in schemas
        ]

        return schemas

